#!/usr/bin/env node
/*!
 * Regenerates lwt-forms.js -- a single-file bundle of every lwt-frm-*.js
 * "form" category element, for pages that would rather load one script
 * than eighteen.
 *
 * Run this any time a new lwt-frm-*.js file is added, or an existing one
 * changes:
 *
 *   node build-lwt-form.js
 *
 * How it works: globs lwt-frm-*.js in this directory (so a newly-added
 * file is picked up automatically, no hardcoded file list to maintain)
 * and concatenates the FULL, UNMODIFIED contents of each one in
 * alphabetical order. Each file keeps its own IIFE wrapper and its own
 * `if (!window.LWT.Element) throw ...` guard -- nothing is merged into a
 * shared scope, so there's no risk of two files' internal helper
 * functions/constants colliding with each other. This also means the
 * bundle is always byte-for-byte equivalent to loading every lwt-frm-*.js
 * file individually; there is no separate "bundle-only" code path to
 * accidentally drift out of sync with the real, tested source files.
 *
 * Still requires lwt-core.js to be loaded first, same as every individual
 * file it contains.
 */
'use strict';

var fs = require('fs');
var path = require('path');

var srcDir = path.join(__dirname, 'elements');
var outDir = __dirname;
var files = fs.readdirSync(srcDir)
  .filter(function (f) { return /^lwt-frm-.*\.js$/.test(f); })
  .sort();

if (!files.length) {
  console.error('No lwt-frm-*.js files found in ' + srcDir);
  process.exit(1);
}

var header =
  '/*!\n' +
  ' * lwt-forms.js -- bundle of every lwt-frm-* element, auto-generated\n' +
  ' * by build-lwt-form.js. DO NOT EDIT THIS FILE BY HAND -- run\n' +
  ' * `node build-lwt-form.js` after adding or changing a lwt-frm-*.js\n' +
  ' * file instead; hand edits here will just get overwritten next build.\n' +
  ' *\n' +
  ' * Generated ' + new Date().toISOString() + ' from:\n' +
  files.map(function (f) { return ' *   ' + f; }).join('\n') + '\n' +
  ' *\n' +
  ' * Requires lwt-core.js to be loaded first.\n' +
  ' */\n\n';

var body = files.map(function (f) {
  var contents = fs.readFileSync(path.join(srcDir, f), 'utf8').replace(/\s+$/, '');
  return '/* ---- ' + f + ' ---- */\n' + contents + '\n';
}).join('\n');

fs.writeFileSync(path.join(outDir, 'lwt-forms.js'), header + body + '\n');
console.log('lwt-forms.js regenerated from ' + files.length + ' files:');
files.forEach(function (f) { console.log('  ' + f); });
